#!/usr/bin/env texlua
--[[---------------------------------------------------------------------------
  tate_off.lua --- compute the tate off@<n>{raise}{shift} punctuation-offset
  table from the IPAex Type1 glyph metrics (T1b, PLAN.md §10.1 tate core).

  Input:  t1disasm output(s) of the ipaex Type1 plane fonts that carry the
          glyphs of the classes named below.  The generator calls this with
          the disassembly files; this script writes a Lua data file
          (tate-off.lua) consumed by make_pdftex_jfm.lua at emission time.

  Derivation (documented at the emission site in make_pdftex_jfm.lua):

  V4 shipout-rotation geometry: the glyph is typeset in the physical
  horizontal "sheet", then rotated CW 90° per glyph (\rotatebox{90}); the
  sheet is rotated CCW 90° at shipout (\rotatebox{-90}). Reading frame:
    reading_x (right) = sheet_y   (raise moves this)
    reading_y (down)  = sheet_x   (kern moves this)

  Yoko ink bbox (x0,x1,y0,y1) in 1/1000-em units (FontMatrix 0.001;
  1em = 1zw). After the CW glyph rotation the ink occupies
    sheet_x in [-y1, -y0],  sheet_y in [x0, x1].
  The rotated-glyph box is normalized to wd=1zw, ht=ght(0.88zw), dp=0.

  JLREQ target corners (JIS X 4051 / JLREQ 4.2.2):
    class 1 (opening brackets): ink at BOTTOM-LEFT of the cell (opens upward
      in the reading frame: the glyph's ink corner hugs the following char,
      which is BELOW it in the column => ink at the top??  JLREQ: 開き括弧の
      字面は行頭側 (上) に張り付く: ink at TOP-RIGHT... the opening bracket's
      ink sits in the UPPER-RIGHT of its cell in tate (its face opens
      downward toward the following text).  Formula below expresses each
      class's target corner as (raise, shift) that move the INK EDGES onto
      the target cell edges; the consumer maps them via its measured slopes.

    raise = (ink right edge -> cell right edge): r = ght_zw - ink_x1_zw
    shift = (ink top edge -> cell top edge):     s = -ink_y1_zw  (sheet-x
            shift of -y1 maps ink sheet_x_min = -y1 to 0 = cell top)

  where ink_x1/ink_y1 are the YOKO ink bbox maxima of the class's
  representative glyph (the first char of the class's chars list).

  Classes emitted (the punctuation-like set; everything else 0/0):
    1, 2 (brackets), 6 (kuten), 7 (touten), 11 (small kana, centered: 0/0 but
    present for completeness), 161 (halfwidth, representative ｡/｢).
-----------------------------------------------------------------------------]]

-- representative glyph per class: (plane-font disassembly file, glyph name)
local REPS = {
  [1]  = { "u30.dis", "uni300C" },  -- 「
  [2]  = { "u30.dis", "uni300D" },  -- 」
  [6]  = { "u30.dis", "uni3002" },  -- 。
  [7]  = { "u30.dis", "uni3001" },  -- 、
  [11] = { "u30.dis", "uni3063" },  -- っ
  [161]= { "uff.dis", "uniFF63" },  -- ｣ (halfwidth forms live in the FF plane)
}

-- zw in pt at the design size the consumer assumes (1zw = 10pt mincho);
-- the emitted values are RAW pt = zw_value * 10.
local ZW_PT = 10
-- rotated-glyph box height in zw (V4 tuner ght)
local GHT_ZW = 0.88

-- fallback when a glyph name is missing from a plane file
local function bbox_of(disfile, gname)
  -- read the bboxes-<plane>.json produced by poc/extbbox3.py if present
  local plane = disfile:match("^u(.+)%.dis$")
  local jf = io.open("bboxes-" .. plane .. ".json", "r")
  if not jf then return nil end
  local data = jf:read("*a"); jf:close()
  local ok, decoded = pcall(require, "dkjson")
  -- texlua ships no json parser guaranteed; parse the simple flat format
  -- {"name":[x0,y0,x1,y1],...} with a pattern scan instead.
  local b = {}
  for name, coords in data:gmatch('"(%S-)"%s*:%s*%[([^%]]*)%]') do
    local t = {}
    for n in coords:gmatch("-?[%d.]+") do t[#t+1] = tonumber(n) end
    b[name] = t
  end
  return b[gname]
end

local out = {}
for c, rep in pairs(REPS) do
  local bb = bbox_of(rep[1], rep[2])
  if bb and #bb == 4 then
    local raise = (GHT_ZW - bb[3] / 1000.0) * ZW_PT
    local shift = -(bb[4] / 1000.0) * ZW_PT
    out[c] = { raise = string.format("%.6f", raise),
               shift = string.format("%.6f", shift) }
  else
    out[c] = { raise = "0.000000", shift = "0.000000" }
  end
end

local fp = io.open("tate-off.lua", "wb")
fp:write("-- generated by tate_off.lua from IPAex Type1 charstring bboxes\n")
fp:write("return {\n")
local keys = {}
for k in pairs(out) do keys[#keys+1] = k end
table.sort(keys)
for _, k in ipairs(keys) do
  fp:write(string.format("  [%d] = { raise = %s, shift = %s },\n",
    k, out[k].raise, out[k].shift))
end
fp:write("}\n")
fp:close()
for _, k in ipairs(keys) do
  io.stderr:write(string.format("off@%d {raise=%s} {shift=%s}\n",
    k, out[k].raise, out[k].shift))
end
