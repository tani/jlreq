--[[---------------------------------------------------------------------------
  pdftexja-mkkinsoku.lua --- generate pdftexja-kinsoku.tex (the default
  per-character kinsoku / jaxspmode table of pdfTeX-ja) from LuaTeX-ja's
  ltj-kinsoku.tex.

  Usage: texlua pdftexja-mkkinsoku.lua [--src=<ltj-kinsoku.tex>] [--out=<file>]

  Only multi-byte characters (U+0080 and above) are kept: under pdfTeX the
  CJK layer sees only those; ASCII/latin kinsoku is TeX's own business.
  jaxspmode values use LuaTeX-ja numbering (0 inhibit, 1 preonly,
  2 postonly, 3 allow). Deterministic: sorted by kind, then code point.
-----------------------------------------------------------------------------]]
kpse.set_program_name("texlua", "lualatex")
local src, out
for _, a in ipairs(arg) do
  if a:sub(1, 6) == "--src=" then src = a:sub(7)
  elseif a:sub(1, 6) == "--out=" then out = a:sub(7)
  else io.stderr:write("unknown argument " .. a .. "\n"); os.exit(1) end
end
src = src or kpse.find_file("ltj-kinsoku.tex")
out = out or "pdftexja-kinsoku.tex"
if not src then io.stderr:write("cannot find ltj-kinsoku.tex\n"); os.exit(1) end

local MODES = { inhibit = 0, preonly = 1, postonly = 2, allow = 3 }
local U = unicode.utf8
local data = { pre = {}, post = {}, jxsp = {} }
local KEY = { prebreakpenalty = "pre", postbreakpenalty = "post", jaxspmode = "jxsp" }

local function charcode(spec)
  if spec:sub(1, 1) == "`" then
    local c = spec:sub(2)
    if c:sub(1, 1) == "\\" then c = c:sub(2) end
    if U.len(c) ~= 1 then return nil end
    return U.byte(c)
  elseif spec:sub(1, 1) == '"' then
    return tonumber(spec:sub(2), 16)
  else
    return tonumber(spec)
  end
end

for line in io.lines(src) do
  local key, ch, val = line:match("^%s*\\ltjsetparameter{(%a+)={(.-),%s*([%w]+)}}")
  if key and KEY[key] then
    local cp = charcode(ch)
    if cp and cp >= 0x80 then
      local v = val
      if KEY[key] == "jxsp" then v = MODES[val] or tonumber(val) end
      v = tonumber(v)
      if v == nil then error("bad value in: " .. line) end
      data[KEY[key]][cp] = v
    end
  end
end

local o = {}
o[#o + 1] = "%% pdftexja-kinsoku.tex -- default kinsoku/jaxspmode table of pdfTeX-ja"
o[#o + 1] = "%% generated by pdftexja-mkkinsoku.lua from ltj-kinsoku.tex -- DO NOT EDIT"
o[#o + 1] = "%% \\ptj@defkinsoku{pre|post|jxsp}{<code point>}{<value>}"
local n = 0
for _, kind in ipairs({ "pre", "post", "jxsp" }) do
  local cps = {}
  for cp in pairs(data[kind]) do cps[#cps + 1] = cp end
  table.sort(cps)
  for _, cp in ipairs(cps) do
    o[#o + 1] = string.format("\\ptj@defkinsoku{%s}{%d}{%d}%% %s", kind, cp,
      data[kind][cp], U.char(cp))
    n = n + 1
  end
end
o[#o + 1] = "\\endinput"
local f = assert(io.open(out, "wb"))
f:write(table.concat(o, "\n") .. "\n")
f:close()
io.stderr:write(string.format("pdftexja-mkkinsoku.lua: wrote %s (%d entries)\n", out, n))
