--[[---------------------------------------------------------------------------
  make_pdftexja_jfm.lua --- generate jlreq's JFM data for pdfTeX-ja.

  pdfTeX-ja reads JFMs as TeX data files ptjfm-<name>.def produced by its
  converter (pdftexja/pdftexja-jfmconv.lua) from LuaTeX-ja JFM Lua files.
  jfm-jlreq.lua / jfm-jlreqv.lua are parameterized by the globals
  jlreq.open_bracket_pos / jlreq.burasage (set by jlreq.cls through
  \directlua under LuaLaTeX), so pdfTeX needs one data file per setting:

    2 directions x 3 open_bracket_pos x burasage on/off = 12 variants
    ptjfm-jlreq[-<s>].def   (yoko, from jfm-jlreq.lua)
    ptjfm-jlreqv[-<s>].def  (tate, from jfm-jlreqv.lua)
    <s> = (b if burasage)(z if zenkakunibu_nibu | n if nibu_tentsuki)

  jlreq.cls computes the same suffix and passes jfm=/tjfm= to pdftexja.
  Under pTeX the nibu_tentsuki geometry is applied by a runtime \everypar
  hook; for pdfTeX-ja it is encoded in the "n" data variants (the
  jfm-jlreq.lua option hook adds the parbdd->opening bracket glue).

  Usage (texlua, repository root):
    texlua make_pdftexja_jfm.lua [--outdir=<dir>]   write the 12 files + manifest
    texlua make_pdftexja_jfm.lua --print-manifest   list the output files
  The manifest ptjfm-jlreq-manifest.lua is the single source of the
  variant list for check_jfm_pdftexja.lua and the Makefile.
-----------------------------------------------------------------------------]]

local scriptdir = arg and arg[0] and arg[0]:match("^(.*)/[^/]*$") or "."
local outdir, print_manifest = nil, false
for _, a in ipairs(arg) do
  if a == "--print-manifest" then print_manifest = true
  elseif a:sub(1, 9) == "--outdir=" then outdir = a:sub(10)
  else io.stderr:write("make_pdftexja_jfm.lua: unknown argument " .. a .. "\n"); os.exit(1) end
end

local MANIFEST = "ptjfm-jlreq-manifest.lua"
local VARIANTS = {}
for _, dir in ipairs({ "yoko", "tate" }) do
  for _, obp in ipairs({ "zenkaku_tentsuki", "zenkakunibu_nibu", "nibu_tentsuki" }) do
    for _, bura in ipairs({ false, true }) do
      local s = (bura and "b" or "")
        .. (obp == "zenkakunibu_nibu" and "z" or (obp == "nibu_tentsuki" and "n" or ""))
      local name = (dir == "tate" and "jlreqv" or "jlreq") .. (s ~= "" and ("-" .. s) or "")
      VARIANTS[#VARIANTS + 1] = { name = name, suffix = s, dir = dir,
        open_bracket_pos = obp, burasage = bura,
        file = "ptjfm-" .. name .. ".def",
        source = dir == "tate" and "jfm-jlreqv.lua" or "jfm-jlreq.lua" }
    end
  end
end

if print_manifest then
  for _, v in ipairs(VARIANTS) do print(v.file) end
  print(MANIFEST)
  os.exit(0)
end

PDFTEXJA_JFMCONV_LIBRARY = true
local conv = dofile(scriptdir .. "/pdftexja/pdftexja-jfmconv.lua")
outdir = outdir or scriptdir
local function path(f) return outdir == "." and f or (outdir .. "/" .. f) end

for _, v in ipairs(VARIANTS) do
  local r = conv.generate {
    jfm = scriptdir .. "/" .. v.source,
    name = v.name,
    pre = string.format("jlreq={open_bracket_pos=%q,burasage=%s}",
      v.open_bracket_pos, tostring(v.burasage)),
    header = { string.format("jlreq variant: dir=%s open_bracket_pos=%s burasage=%s",
      v.dir, v.open_bracket_pos, tostring(v.burasage)) },
    out = path(v.file),
  }
  io.stderr:write(string.format("make_pdftexja_jfm.lua: wrote %s (classes %d, chars %d, pairs %d)\n",
    v.file, r.classes, r.chars, r.pairs))
end

local o = {}
o[#o + 1] = "-- " .. MANIFEST .. " --- generated by make_pdftexja_jfm.lua"
o[#o + 1] = "-- DO NOT EDIT; regenerate with `make pdftexja-jfm`."
o[#o + 1] = "return {"
o[#o + 1] = "  converter_version = " .. string.format("%q", conv.version) .. ","
o[#o + 1] = "  variants = {"
for _, v in ipairs(VARIANTS) do
  o[#o + 1] = string.format("    { name = %q, suffix = %q, file = %q, dir = %q,",
    v.name, v.suffix, v.file, v.dir)
  o[#o + 1] = string.format("      open_bracket_pos = %q, burasage = %s },",
    v.open_bracket_pos, tostring(v.burasage))
end
o[#o + 1] = "  },"
o[#o + 1] = "}"
local f = assert(io.open(path(MANIFEST), "wb"))
f:write(table.concat(o, "\n") .. "\n")
f:close()
